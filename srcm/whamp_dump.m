    struct('m',2,'n',1,'t',0.05,'a',1,'b',0,'d',1,'vd',0), ...
    struct('m',16,'n',0.5,'t',0.01,'a',5,'b',0,'d',1,'vd',1), ...
    electrons});

modelLossCone = plasma(100, { ...
    struct('m',16,'n',1,'t',10,'a',5,'b',2,'d',1.5,'vd',1), ...
    electrons});

modelDrift = plasma(100, { ...
    struct('m',16,'n',1,'t',10,'a',1,'b',0,'d',1,'vd',-0.5), ...
    electrons});

P = @(varargin) params(varargin{:});
cases = {
    struct('name','default','model',modelDefault,'params',P());
    struct('name','single_p0z','model',modelDefault, ...
        'params',P('fstart',0.1,'kperp',0,'kpar',0.0022,'useLog',0));
    struct('name','sweep_p_first','model',modelDefault, ...
        'params',P('fstart',0.1,'kperp',[0 0.01 0.04],'kpar',0.0022, ...
        'varyKzFirst',0,'useLog',0));
    struct('name','sweep_z_first','model',modelDefault, ...
        'params',P('fstart',0.1,'kperp',0,'kpar',[0.0022 0.0022 0.01], ...
        'varyKzFirst',1,'useLog',0));
    struct('name','sweep_both','model',modelDefault, ...
        'params',P('fstart',0.1,'kperp',[0 0.01 0.03], ...
        'kpar',[0.0022 0.0022 0.0088],'varyKzFirst',1,'useLog',0));
    struct('name','sweep_neg_step','model',modelDefault, ...
        'params',P('fstart',0.1,'kperp',[0 -0.01 0.05],'kpar',0.0022, ...
        'varyKzFirst',1,'useLog',0));
    struct('name','log_axes','model',modelDefault, ...
        'params',P('fstart',0.1,'kperp',[-2.3 0.1 -1.8], ...
        'kpar',[-3 0.1 -2.7],'useLog',1,'varyKzFirst',1));
    struct('name','log_axes_zfirst0','model',modelDefault, ...
        'params',P('fstart',0.1,'kperp',[-2.3 0.1 -1.8], ...
        'kpar',[-3 0.1 -2.7],'useLog',1,'varyKzFirst',0));
    struct('name','three_species','model',modelThree, ...
        'params',P('fstart',0.1,'kperp',0,'kpar',0.0022,'useLog',0));
    struct('name','ex2','model',modelEx2, ...
        'params',P('fstart',0.1,'kperp',[0 0.01 0.02], ...
        'kpar',[0.001 0.0022 0.005],'useLog',0,'varyKzFirst',1));
    struct('name','heavy_damping','model',modelDefault, ...
        'params',P('fstart',1.5,'kperp',2,'kpar',0.5,'useLog',0));
    struct('name','no_convergence','model',modelDefault, ...
        'params',P('fstart',0.0001,'kperp',0,'kpar',0.0022,'useLog',0));
    struct('name','maxiter_3','model',modelDefault, ...
        'params',P('fstart',0.1,'kperp',0,'kpar',0.0022,'useLog',0, ...
        'maxIterations',3));
    struct('name','maxiter_1','model',modelDefault, ...
        'params',P('fstart',0.1,'kperp',0,'kpar',0.0022,'useLog',0, ...
        'maxIterations',1));
    struct('name','loss_cone','model',modelLossCone, ...
        'params',P('fstart',0.1,'kperp',[0 0.01 0.02],'kpar',0.0022, ...
        'useLog',0,'varyKzFirst',1));
    struct('name','drift','model',modelDrift, ...
        'params',P('fstart',0.1,'kperp',[0 0.01 0.02],'kpar',0.0022, ...
        'useLog',0,'varyKzFirst',1));
    struct('name','kz_zero','model',modelDefault, ...
        'params',P('fstart',0.1,'kperp',[0 0.01 0.02],'kpar',0, ...
        'useLog',0,'varyKzFirst',1));
    struct('name','high_b','model',plasma(300,{oxygen,electrons}), ...
        'params',P('fstart',0.1,'kperp',[0 0.01 0.02],'kpar',0.0022, ...
        'useLog',0,'varyKzFirst',1));
    struct('name','low_b','model',plasma(10,{oxygen,electrons}), ...
        'params',P('fstart',0.1,'kperp',[0 0.01 0.02],'kpar',0.0022, ...
        'useLog',0,'varyKzFirst',1));
    struct('name','fstart_high','model',modelDefault, ...
        'params',P('fstart',0.9,'kperp',[0 0.01 0.02],'kpar',0.0022, ...
        'useLog',0,'varyKzFirst',1));
    struct('name','sweep_long','model',modelDefault, ...
        'params',P('fstart',0.1,'kperp',[0 0.005 0.05],'kpar',0.0022, ...
        'varyKzFirst',0,'useLog',0));
    struct('name','species_defaults_partial','model',plasma(100, ...
        {struct('m',16,'n',1,'t',10,'a',5,'vd',1), struct('m',0,'n',1,'t',100)}), ...
        'params',P('fstart',0.1,'kperp',0,'kpar',0.0022,'useLog',0));
    struct('name','struct_species','model',plasma(100,oxygen), ...
        'params',P('fstart',0.1,'kperp',0,'kpar',0.0022,'useLog',0));
    struct('name','bad_maxiter','model',modelDefault, ...
        'params',P('maxIterations',0));
    struct('name','bad_fstart','model',modelDefault,'params',P('fstart',0));
    struct('name','bad_uselog','model',modelDefault,'params',P('useLog',2));
    struct('name','bad_kstep','model',modelDefault, ...
        'params',P('kperp',[0 0 1],'useLog',0));
    struct('name','bad_species','model',plasma(100,struct('m',16,'n','x')), ...
        'params',P());
    struct('name','bad_b','model',plasma(-1,oxygen), 'params',P());
    struct('name','too_many_species','model', ...
        plasma(100,repmat({oxygen},1,11)),'params',P());
    };
end

function model = plasma(B, species)
%PLASMA Build a PlasmaModel without struct brace expansion pitfalls.
%   SPECIES is either a cell array of species structures or one structure.
model = struct('B',B);
model.Species = species;
end

function p = params(varargin)
p = struct();
for k = 1:2:numel(varargin)
    p.(varargin{k}) = varargin{k+1};
end
end
