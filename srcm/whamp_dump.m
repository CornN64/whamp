modelEx2 = plasma(50, { ...
    struct('m',1,'n',5,'t',1,'a',1,'b',0,'d',1,'vd',0), ...
    struct('m',1,'n',5,'t',0.01,'a',2,'b',0,'d',1,'vd',2), ...
    electrons});

