function whamp_dump(outFile)
%WHAMP_DUMP Regression harness: run a fixed case set and dump every output
%   field at full precision so a refactor can be checked for bit-identical
%   behaviour.  Usage:  whamp_dump('before.txt')
%
% Cases are chosen to exercise each code path: single points, both sweep
% orders, negative steps, log axes, extra species, heavy damping,
% non-convergence, tiny maxIterations, and zero kperp/kpar (which take the
% guarded DP/DZ branches).

if nargin < 1
    outFile = 'dump.txt';
end

cases = test_cases();
fid = fopen(outFile, 'wt');
if fid < 0
    error('whamp_dump:Open', 'Cannot open %s for writing.', outFile);
end
cleanup = onCleanup(@() fclose(fid));

for k = 1:numel(cases)
    tc = cases{k};
    fprintf(fid, '=== CASE %s ===\n', tc.name);
    try
        O = whamp(tc.model, tc.params);
    catch ME
        fprintf(fid, 'ERROR %s: %s\n', ME.identifier, ME.message);
        continue
    end
    names = {'kperp','kpar','f','Ex','Ey','Ez','Bx','By','Bz', ...
        'Sx','Sy','Sz','EB','VGP','VGZ','SGP','SGZ','u', ...
        'flagSolutionFound','flagTooHeavilyDamped','flagNoConvergence'};
    for n = 1:numel(names)
        v = O.(names{n});
        fprintf(fid, '-- %s [%dx%d]\n', names{n}, size(v,1), size(v,2));
        for j = 1:numel(v)
            if isnumeric(v)
                fprintf(fid, '%.20g %.20g\n', real(v(j)), imag(v(j)));
            else
                fprintf(fid, '%d 0\n', v(j));
            end
        end
    end
end
end

function cases = test_cases()
